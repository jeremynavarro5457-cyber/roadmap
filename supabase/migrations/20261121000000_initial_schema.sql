-- ─────────────────────────────────────────────
-- profiles : un profil par utilisateur (lié à auth.users)
-- ─────────────────────────────────────────────
create table public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  firstname   text,
  lastname    text,
  email       text not null unique,
  avatar_url  text,
  role        text not null default 'user'
              check (role in ('user', 'admin')),
  created_at  timestamptz not null default now()
);

-- ─────────────────────────────────────────────
-- modules : grandes zones fonctionnelles du produit
-- ─────────────────────────────────────────────
create table public.modules (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  color       text not null,              -- couleur hex, ex. '#E8634A'
  description text,
  created_at  timestamptz not null default now()
);

-- ─────────────────────────────────────────────
-- sprints : périodes de travail (pas de nom, on affiche « Sprint {id} »)
-- ─────────────────────────────────────────────
create table public.sprints (
  id          bigint generated by default as identity primary key,
  goal        text,
  start_date  date not null,
  end_date    date not null,
  status      text not null default 'planned'
              check (status in ('planned', 'active', 'completed')),
  created_at  timestamptz not null default now()
);

-- ─────────────────────────────────────────────
-- features : les évolutions du produit
-- ─────────────────────────────────────────────
create table public.features (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text not null,
  description text,
  status      text not null default 'backlog'
              check (status in ('backlog', 'todo', 'in_progress', 'done', 'cancelled')),
  priority    text not null default 'medium'
              check (priority in ('critical', 'high', 'medium', 'low', 'nice_to_have')),
  effort      text
              check (effort in ('xs', 's', 'm', 'l', 'xl')),
  impact      text not null default 'medium'
              check (impact in ('low', 'medium', 'high')),
  module_id   bigint references public.modules (id),
  sprint_id   bigint references public.sprints (id),   -- null = dans le backlog
  assigned_to uuid references public.profiles (id)
);

-- ─────────────────────────────────────────────
-- comments : fil de discussion d'une feature
-- ─────────────────────────────────────────────
create table public.comments (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  content     text not null,
  feature_id  bigint not null references public.features (id),
  author_id   uuid not null references public.profiles (id)
);

-- ─────────────────────────────────────────────
-- Création automatique du profil à l'inscription d'un utilisateur
-- ─────────────────────────────────────────────
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

